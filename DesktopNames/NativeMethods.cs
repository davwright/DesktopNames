    public static INPUT CreateKeyInput(byte vk, bool keyUp)
    {
        var input = new INPUT { type = 1 }; // INPUT_KEYBOARD
        input.union.ki.wVk = vk;
        input.union.ki.dwFlags = keyUp ? 0x0002u : 0u; // KEYEVENTF_KEYUP
        return input;
    }

